#ifndef __SEG_H
#define __SEG_H

#include "stm32f10x.h"

#define SEG_DIGIT_COUNT 4

/**
 * ================================================================================
 * 7段数码管硬件接线说明
 * ================================================================================
 * 
 * 段驱动引脚 (PA0~PA7): 控制每一位数字的7个段(a-g)和小数点(dp)
 *   PA0=a(顶)    PA1=b(右上)  PA2=c(右下)  PA3=d(底)
 *   PA4=e(左下)  PA5=f(左上)  PA6=g(中)    PA7=dp(小数点)
 *
 * 位选驱动引脚 (PB12~PB15): 控制哪一位数字被激活显示
 *   PB12 = 数字位0 (个位/ones)
 *   PB13 = 数字位1 (十位/tens)
 *   PB14 = 数字位2 (百位/hundreds)
 *   PB15 = 数字位3 (千位/thousands或V标记)
 *
 * ================================================================================
 * 显示方式选择: 共阳极 vs 共阴极
 * ================================================================================
 *
 * 您的硬件是哪一种？在下面定义对应的宏:
 *
 * ┌─────────────────────────────────────────────────────────────┐
 * │ 共阳极 (Common Anode)                                        │
 * ├─────────────────────────────────────────────────────────────┤
 * │ • 数码管所有段的公共端接电源(+3.3V)                        │
 * │ • 要显示某段 → 该段输出0(低电平),LED发光                   │
 * │ • 要关闭某段 → 该段输出1(高电平)                           │
 * │ • 要显示某位 → 该位的位选输出0(低电平),激活该位           │
 * │ • 要关闭某位 → 该位的位选输出1(高电平)                     │
 * │                                                               │
 * │ 在下面 #define SEG_COMMON_ANODE 来启用此模式               │
 * └─────────────────────────────────────────────────────────────┘
 *
 * ┌─────────────────────────────────────────────────────────────┐
 * │ 共阴极 (Common Cathode) - 默认模式                          │
 * ├─────────────────────────────────────────────────────────────┤
 * │ • 数码管所有段的公共端接地(GND)                            │
 * │ • 要显示某段 → 该段输出1(高电平),LED发光                   │
 * │ • 要关闭某段 → 该段输出0(低电平)                           │
 * │ • 要显示某位 → 该位的位选输出1(高电平),激活该位           │
 * │ • 要关闭某位 → 该位的位选输出0(低电平)                     │
 * │                                                               │
 * │ 此为默认模式,无需特殊定义                                   │
 * └─────────────────────────────────────────────────────────────┘
 *
 * ================================================================================
 * 使用说明: 如何配置您的硬件类型
 * ================================================================================
 *
 * 【方式1】 直接在此文件修改 (推荐)
 *   在下面找到这一行,取消注释:
 *     // #define SEG_COMMON_ANODE
 *   改为:
 *     #define SEG_COMMON_ANODE
 *
 * 【方式2】 在 main.c 编译前定义
 *   在 main.c 的最开始添加:
 *     #define SEG_COMMON_ANODE
 *   然后再 #include "seg.h"
 *
 * 【方式3】 Keil 工程配置
 *   在 Keil 的 "Project Options" → "C/C++" → "Define"
 *   输入: SEG_COMMON_ANODE
 *
 * ================================================================================
 * 识别您的数码管类型
 * ================================================================================
 *
 * 1. 查看数码管的标签或引脚图:
 *    - 如果公共端标记为 "CC" 或 "COM",查看是否接电源(+) 或地(GND)
 *    - 共阳极: 公共端接 +3.3V
 *    - 共阴极: 公共端接 GND
 *
 * 2. 实验测试 (如果不确定):
 *    - 先使用默认模式(共阴极)运行程序
 *    - 如果显示反白(亮的地方黑,黑的地方亮) → 切换为共阳极
 *    - 如果正常显示 → 保持共阴极
 *
 * ================================================================================
 */

// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
// 【关键配置】: 根据您的硬件选择下面的一行
// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

// 取消注释下面这一行,如果您的数码管是共阳极(公共端接+3.3V)
#define SEG_COMMON_ANODE

// 注释: 如果上面没有定义 SEG_COMMON_ANODE,将使用共阴极模式(默认)

// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

#ifdef SEG_COMMON_ANODE
// 共阳极配置: 段是低电平点亮，位选是高电平激活（直接驱动模式）
// 注意：如果您使用了PNP三极管驱动位选，请将DIGIT_ACTIVE_HIGH改为0
#define SEG_ACTIVE_HIGH 0
#define DIGIT_ACTIVE_HIGH 1
#else
// 共阴极配置: 段是高电平点亮，位选是低电平激活（重要！）
#define SEG_ACTIVE_HIGH 1
#define DIGIT_ACTIVE_HIGH 0  // 共阴极位选也是低电平激活！
#endif

/**
 * 函数声明
 */
void SEG_Init(void);                              // 初始化7段显示硬件
void SEG_Task(void);                              // 每1ms调用一次,刷新显示
void SEG_DisplayRaw(uint16_t value);              // 显示0~4095的原始ADC值
void SEG_DisplayVoltage(uint32_t voltage_mv);     // 显示电压值(mV),格式X.XXV
void SEG_TestSingleSegment(uint8_t segment_bit); // 测试单个段（0-7对应a-dp）
void SEG_DisplaySingleDigit(uint8_t digit_pos, uint8_t value); // 在指定位显示数字

#endif
